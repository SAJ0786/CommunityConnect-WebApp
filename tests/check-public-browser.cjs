const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const origin = 'http://127.0.0.1:5183';
const output = path.resolve(process.argv[2] || '.qa-public-preview/evidence');
fs.mkdirSync(output, { recursive: true });
(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  const context = await browser.newContext();
  const errors = [], remote = [], results = [];
  await context.route('**/*', route => {
    if (new URL(route.request().url()).origin !== origin) { remote.push(route.request().url()); return route.abort(); }
    return route.continue();
  });
  const page = await context.newPage();
  page.on('pageerror', error => errors.push(error.message));
  const check = (name, value = true) => { assert.ok(value, name); results.push(name); };
  const go = async url => { await page.goto(origin + url); await page.waitForLoadState('networkidle'); };
  const state = async value => { await page.evaluate(value => sessionStorage.setItem('public-fixture-state', value), value); await page.reload(); await page.waitForLoadState('networkidle'); };
  try {
    for (const width of [320, 390, 768, 1440]) {
      await page.setViewportSize({ width, height: 900 });
      for (const [name, url] of [['directory', '/businesses'], ['business', '/businesses/view/example'], ['promotions', '/businesses/promotions']]) {
        await go(url);
        await page.locator('h1').waitFor();
        check(`${name} ${width}px has no horizontal overflow`, await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
        check(`${name} ${width}px never mounts account orchestration`, await page.evaluate(() => !window.__legacyMounted));
        if ([390, 1440].includes(width)) await page.screenshot({ path: path.join(output, `${name}-${width}.png`), fullPage: true });
      }
    }
    await go('/businesses');
    const cityPicker = page.getByRole('combobox', { name: 'Your city' });
    await cityPicker.focus();
    await page.keyboard.press('ArrowDown');
    await page.getByRole('listbox', { name: 'Your city' }).waitFor();
    await page.keyboard.press('End');
    await page.keyboard.press('Enter');
    check('city picker keyboard selects the last option', (await cityPicker.innerText()).trim() === 'Rest of Australia');
    await page.keyboard.press('ArrowDown');
    await page.keyboard.press('Home');
    await page.keyboard.press('Enter');
    check('city picker keyboard returns to Sydney', (await cityPicker.innerText()).trim() === 'Sydney');
    await cityPicker.click();
    await page.keyboard.press('Escape');
    check('city picker Escape dismisses the menu', await cityPicker.getAttribute('aria-expanded') === 'false');
    const disclosure = page.getByLabel('Details for Example Community Catering', { exact: true });
    check('business starts compact', await disclosure.locator('..').getAttribute('open') === null);
    await disclosure.focus();
    await page.keyboard.press('Enter');
    check('business keyboard expansion reveals contacts', await page.getByRole('link', { name: 'Call business', exact: true }).isVisible());
    await page.keyboard.press('Enter');
    check('business keyboard collapse hides contacts', !(await page.getByRole('link', { name: 'Call business', exact: true }).isVisible()));
    await page.getByLabel('Search businesses or services').fill('catering');
    await page.getByRole('group', { name: 'Business categories', exact: true }).getByRole('button', { name: 'Food & Catering', exact: true }).click();
    await page.getByLabel('Details for Example Community Catering', { exact: true }).click();
    await page.getByRole('link', { name: 'View Example Community Catering →', exact: true }).click();
    await page.getByRole('heading', { name: 'Example Community Catering', exact: true }).waitFor();
    check('card opens a dedicated business URL', page.url().includes('/businesses/view/example'));
    await page.reload();
    await page.getByRole('heading', { name: 'Example Community Catering', exact: true }).waitFor();
    check('direct detail survives refresh', await page.title() === 'Example Community Catering | Community Connect Australia');
    await page.goBack();
    await page.waitForLoadState('networkidle');
    await page.getByLabel('Search businesses or services').waitFor();
    check('browser back restores search and category', await page.getByLabel('Search businesses or services').inputValue() === 'catering' && await page.getByRole('group', { name: 'Business categories', exact: true }).getByRole('button', { name: 'Food & Catering', exact: true }).getAttribute('aria-pressed') === 'true');
    await page.goForward();
    await page.waitForLoadState('networkidle');
    await page.getByRole('link', { name: '← Back to businesses' }).click();
    await page.waitForLoadState('networkidle');
    await page.getByLabel('Search businesses or services').waitFor();
    check('explicit back link restores search', await page.getByLabel('Search businesses or services').inputValue() === 'catering');
    await page.getByRole('combobox', { name: 'Your city' }).click();
    await page.getByRole('option', { name: 'Melbourne', exact: true }).click();
    await page.getByLabel('Details for Example Melbourne Workshop', { exact: true }).click();
    await page.getByRole('link', { name: 'View Example Melbourne Workshop →', exact: true }).click();
    await page.getByRole('heading', { name: 'Example Melbourne Workshop', exact: true }).waitFor();
    check('changing city resets irrelevant category', !page.url().includes('category='));
    await go('/businesses/view/melbourne');
    await page.getByRole('link', { name: '← Back to businesses' }).click();
    await page.getByLabel('Your city').waitFor();
    check('direct detail back chooses the business city', (await page.getByRole('combobox', { name: 'Your city' }).innerText()).trim() === 'Melbourne');

    await go('/businesses/view/example');
    check('private street absent from page and map link', !(await page.locator('body').innerText()).includes('PRIVATE STREET') && !(await page.getByRole('link', { name: 'View location ↗' }).getAttribute('href')).includes('PRIVATE'));
    check('public contacts use correct schemes', (await page.getByRole('link', { name: 'Call business' }).getAttribute('href')).startsWith('tel:') && (await page.getByRole('link', { name: 'Email business' }).getAttribute('href')).startsWith('mailto:'));
    check('only current visible offers appear', !/EXPIRED OFFER|FUTURE OFFER|HIDDEN OFFER|PENDING OFFER|ORPHAN OFFER/.test(await page.locator('body').innerText()));
    check('detail shows offer conditions', (await page.locator('#promotions').innerText()).includes('Mention COMMUNITY'));
    await page.evaluate(() => Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText: async text => { window.__copied = text; } } }));
    await page.getByRole('button', { name: 'Copy link', exact: true }).click();
    await page.getByText('Business link copied.', { exact: true }).waitFor();
    check('copy provides canonical URL without filters', await page.evaluate(() => window.__copied) === origin + '/businesses/view/example');
    await page.evaluate(() => Object.defineProperty(navigator, 'share', { configurable: true, value: async data => { window.__shared = data; } }));
    await page.getByRole('button', { name: 'Share business', exact: true }).click();
    check('share sheet receives business URL', await page.evaluate(() => window.__shared.url) === origin + '/businesses/view/example');
    await page.evaluate(() => { Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText: async () => { throw new Error('Unavailable'); } } }); Object.defineProperty(navigator, 'share', { configurable: true, value: undefined }); });
    await page.getByRole('button', { name: 'Share business', exact: true }).click();
    await page.getByLabel('Business link', { exact: true }).waitFor();
    check('unavailable clipboard/share offers selectable link', await page.getByLabel('Business link', { exact: true }).inputValue() === origin + '/businesses/view/example');
    await page.getByRole('button', { name: 'Copy link', exact: true }).focus();
    await page.keyboard.press('Tab');
    check('manual link is keyboard accessible', await page.getByLabel('Business link', { exact: true }).evaluate(el => el === document.activeElement));

    await go('/businesses/promotions');
    check('sponsored offer comes first', await page.locator('.directory-promotion h3').first().innerText() === 'Community catering special');
    await page.getByRole('combobox', { name: 'Your city' }).click();
    await page.getByRole('option', { name: 'Melbourne', exact: true }).click();
    await page.getByRole('heading', { name: 'Melbourne workshop offer' }).waitFor();
    check('promotion city filtering excludes Sydney', !(await page.locator('main').innerText()).includes('Community catering special'));
    await page.reload();
    await page.getByLabel('Your city').waitFor();
    check('promotion city survives refresh', (await page.getByRole('combobox', { name: 'Your city' }).innerText()).trim() === 'Melbourne');
    await page.getByRole('link', { name: /View offer at/ }).click();
    await page.locator('#promotions').waitFor();
    check('offer opens linked business and promotions anchor', page.url().includes('/view/melbourne?city=melbourne#promotions'));

    await go('/businesses/view/unknown');
    await page.getByRole('heading', { name: 'Business not available', exact: true }).waitFor();
    check('missing business has an unavailable state');
    await state('cached');
    await page.getByRole('heading', { name: 'Business not available offline' }).waitFor();
    check('cached missing business does not claim deletion');
    await go('/businesses/view/example');
    check('cached listing and offers visibly labelled', (await page.locator('main').innerText()).includes('Showing a saved listing') && (await page.locator('main').innerText()).includes('Saved promotions may be out of date'));
    await state('businesses-error');
    await page.getByRole('heading', { name: 'Business unavailable', exact: true }).waitFor();
    await page.evaluate(() => sessionStorage.setItem('public-fixture-state', 'ready'));
    await page.getByRole('button', { name: 'Try again', exact: true }).click();
    await page.getByRole('heading', { name: 'Example Community Catering', exact: true }).waitFor();
    check('business feed recovers on retry');
    await state('promotions-error');
    check('promotion error leaves business usable', await page.getByRole('link', { name: 'Call business' }).isVisible());
    await page.evaluate(() => sessionStorage.setItem('public-fixture-state', 'ready'));
    await page.getByRole('button', { name: 'Retry promotions' }).click();
    await page.getByRole('heading', { name: 'Community catering special' }).waitFor();
    check('promotion feed recovers independently');
    await page.evaluate(() => { sessionStorage.setItem('public-fixture-state', 'removed'); window.dispatchEvent(new Event('public-fixture-update')); });
    await page.getByRole('heading', { name: 'Business not available', exact: true }).waitFor();
    check('live parent removal clears details and offers', !(await page.locator('body').innerText()).includes('Community catering special'));
    await state('loading');
    await page.getByText('Loading business…').waitFor();
    check('loading does not flash missing state', !(await page.locator('body').innerText()).includes('Business not available'));
    await state('images');
    check('broken images are removed without breaking details', await page.locator('.directory-cover, .directory-logo').count() === 0 && await page.getByRole('heading', { name: 'Example Community Catering', exact: true }).isVisible());
    await state('empty');
    await go('/businesses/promotions');
    await page.getByRole('heading', { name: 'No active promotions' }).waitFor();
    check('empty promotions state');
    await state('ready');
    await go('/businesses/view/%25invalid');
    await page.getByRole('heading', { name: 'Business not available', exact: true }).waitFor();
    check('invalid/missing identifiers do not crash');
    await page.evaluate(() => sessionStorage.setItem('communityWebExperience', 'businesses'));
    await page.getByRole('link', { name: 'Events', exact: true }).click();
    await page.getByRole('heading', { name: 'Existing Events route preserved' }).waitFor();
    check('Events navigation restores the Events experience', await page.evaluate(() => sessionStorage.getItem('communityWebExperience')) === 'events');
    await go('/?event=example');
    await page.getByRole('heading', { name: 'Existing Events route preserved' }).waitFor();
    check('existing root event query is delegated unchanged', new URL(page.url()).search === '?event=example');
    assert.deepEqual(errors, [], 'Browser runtime errors');
    assert.deepEqual(remote, [], 'Offline preview must never attempt remote requests');
    fs.writeFileSync(path.join(output, 'browser-results.json'), JSON.stringify({ results, errors, remote }, null, 2));
    console.log(`PASS: ${results.length} public browsing checks; no remote requests or runtime errors.`);
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
